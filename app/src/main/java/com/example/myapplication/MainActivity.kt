data class Cart(
    val products: List<Product>
)

data class Product(
    val id: Int,
    val name: String,
    val price: Int
)

class MainActivity : ComponentActivity() {
    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        setContent {
            ShoppingCartScreen()
        }
    }
}

@Composable
fun ShoppingCartScreen() {
    val context = LocalContext.current

    var products by remember {
        mutableStateOf(
            listOf(
                Product(0, "Товар #1", 100),
                Product(1, "Товар #2", 150),
                Product(2, "Товар #3", 56)
            )
        )
    }

    // Сумма вычисляется из состояния, а не накапливается в поле класса
    val totalSum = products.sumOf { it.price }

    Column(modifier = Modifier.padding(16.dp)) {
        for (product in products) {
            Text(text = product.name + " - " + product.price + " рублей")
        }

        Spacer(modifier = Modifier.height(10.dp))
        Text(text = "Товаров на сумму: $totalSum рублей")

        AddProductSection(
            onAdd = {
                val newProduct = Product(
                    id = products.size,
                    name = "Товар #${products.size + 1}",
                    price = Random.nextInt(0, 100)
                )
                val newProducts = products + newProduct
                products = newProducts

                // Сообщение показывается при добавлении, а не при рекомпозиции
                if (newProducts.sumOf { it.price } > 500) {
                    Toast.makeText(
                        context,
                        "Доставка бесплатная!",
                        Toast.LENGTH_SHORT
                    ).show()
                }
            }
        )

        RemoveProductSection(
            isVisible = products.isNotEmpty(),
            onRemove = { products = products.dropLast(1) }
        )
    }
}

@Composable
fun AddProductSection(
    onAdd: () -> Unit
) {
    Button(onClick = onAdd) {
        Text(text = "Добавить товар")
    }
}

@Composable
fun RemoveProductSection(
    isVisible: Boolean,
    onRemove: () -> Unit
) {
    if (isVisible) {
        Button(onClick = onRemove) {
            Text(text = "Удалить товар")
        }
    }
}







